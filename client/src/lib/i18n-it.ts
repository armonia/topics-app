/**
 * client/src/lib/i18n-it.ts - the ITALIAN catalogue, in its own module.
 *
 * The English one moved out first, for bundle size (`i18n-en.ts` explains it).
 * This one moved for the other reason: it is EAGER and stays eager - a static
 * import, same bytes on first paint - but at ~1.900 lines inside `i18n.ts` it
 * made that file the place every branch had to meet. `check:bloat` caught it
 * four lines over its ceiling and the growth was thirty legitimate keys from
 * one landed feature: nothing to remove, so the file had to stop being two
 * things at once. `i18n.ts` is now the machinery (`t`, `interpolate`,
 * `resolveLocale`, `ensureLocaleLoaded`); the two catalogues are symmetric
 * modules beside it.
 *
 * Keys are `surface.thing`, and the surface is the one in the INTERFACE, not
 * the file: whoever asks "where is this text" starts from what they can see.
 */
