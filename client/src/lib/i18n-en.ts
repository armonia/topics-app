/**
 * client/src/lib/i18n-en.ts — the ENGLISH catalogue, in its own module so it is
 * not in the eager bundle.
 *
 * It used to live beside the Italian one in `i18n.ts`, which every screen
 * imports, so both languages shipped to everyone on first paint. The default
 * locale is Italian (`FALLBACK_LOCALE`, and `resolveLocale` deliberately does
 * not read the browser), so for almost every session these ~880 lines were
 * downloaded, parsed and never read. On 2026-08-15 that pushed the eager entry
 * 55 KB raw / 17 KB gzip past its budget and `check:bundle` said so.
 *
 * It is loaded on demand by `ensureLocaleLoaded('en')` the first time anything
 * asks for English. Until it lands `t()` answers in Italian, which is exactly
 * what it already did for a key the English catalogue was missing, so the
 * degraded state is one the app was always able to be in.
 */
