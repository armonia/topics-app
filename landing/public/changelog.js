/* Topics landing: changelog renderer. Vanilla, no deps. Populates any
   [data-changelog] container from ./changelog.json (generated by
   `bun run changelog`). data-limit="N" caps the number of versions shown;
   omit or "all" for the full history. Used by both index.html (teaser) and
   changelog.html (full). */
(() => {
  'use strict';
  const containers = [...document.querySelectorAll('[data-changelog]')];
  if (!containers.length) return;

  const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
  const SECTIONS = [['new', 'New'], ['fixes', 'Fixes'], ['perf', 'Performance']];

  const renderVersion = (v) => {
    const secs = SECTIONS.map(([key, label]) => {
      const items = (v.sections && v.sections[key]) || [];
      if (!items.length) return '';
      const lis = items
        .map((e) => `<li>${e.scope ? `<span class="cl-scope">${esc(e.scope)}</span> ` : ''}${esc(e.text)}</li>`)
        .join('');
      return `<div class="cl-sec"><h4 class="cl-sec__h cl-sec__h--${key}">${label}</h4><ul>${lis}</ul></div>`;
    }).join('');
    if (!secs) return '';
    const date = v.date ? `<time class="cl-date mono">${esc(v.date)}</time>` : '';
    return `<article class="cl-rel card" id="v${esc(v.version)}"><header class="cl-rel__head"><a class="cl-ver" href="#v${esc(v.version)}">v${esc(v.version)}</a>${date}</header><div class="cl-secs">${secs}</div></article>`;
  };

  fetch('./changelog.json')
    .then((r) => (r.ok ? r.json() : Promise.reject(new Error(String(r.status)))))
    .then((data) => {
      for (const el of containers) {
        const limit = el.dataset.limit;
        const versions = limit && limit !== 'all' ? data.slice(0, Number(limit)) : data;
        el.innerHTML = versions.map(renderVersion).join('');
        // let the shared scroll-reveal observer (app.js) pick up new .reveal nodes,
        // or just show them if it already ran / isn't present.
        el.classList.add('in');
      }
      // If a #vX.Y.Z was in the URL, jump to it now that content exists.
      if (location.hash && document.querySelector(location.hash)) {
        document.querySelector(location.hash).scrollIntoView();
      }
    })
    .catch(() => {
      for (const el of containers) {
        el.innerHTML =
          '<p class="cl-empty">Changelog unavailable — see the <a href="https://github.com/armonia/topics-app/releases">releases page</a>.</p>';
      }
    });
})();
